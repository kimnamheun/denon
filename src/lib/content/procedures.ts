const BY_TAG = new Map(PROCEDURE_GUIDES.map((g) => [g.tag, g]));

export function getProcedureGuide(tag: string): ProcedureGuide | null {
  return BY_TAG.get(tag) ?? null;
}

/**
 * 견적서 문장(치료 계획·추가 항목 이름)에서 나오는 시술 안내를 찾는다.
 * 낱말이 들어 있으면 그 시술로 본다. 가이드 목록 순서대로 돌려준다.
 */
export function findGuidesInText(texts: ReadonlyArray<string | null | undefined>): ProcedureGuide[] {
  const joined = texts.filter(Boolean).join("\n");
  if (!joined) return [];
  return PROCEDURE_GUIDES.filter((g) => g.keywords.some((k) => joined.includes(k)));
}
